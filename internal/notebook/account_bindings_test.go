func TestLinkedNotebookCreateIsIdempotentAndPreservesState(t *testing.T) {
	ctx := context.Background()
	p := NewWithShared(t.TempDir(), fakeShared{})
	first, created, err := p.CreateWithSourceResult(ctx, "Original name", "playground-1")
	if err != nil || !created {
		t.Fatalf("initial bind: created=%v err=%v", created, err)
	}
	a, err := p.get(first.ID)
	if err != nil {
		t.Fatal(err)
	}
	a.mu.Lock()
	a.status.Email = "test@example.com"
	a.status.State = "ready"
	a.status.RequestCount = 15
	a.status.SuccessCount = 12
	a.status.CooldownUntil = time.Now().Add(time.Minute)
	a.status.Notebooks = []Notebook{{ID: "notebook-1", Title: "Remember Me"}}
	a.mu.Unlock()
	if err := p.save(); err != nil {
		t.Fatal(err)
	}
	again, created, err := p.CreateWithSourceResult(ctx, "This must not rename", "playground-1")
	if err != nil || created {
		t.Fatalf("duplicate returned created=%v err=%v", created, err)
	}
	if again.ID != first.ID || again.Label != "Original name" ||
		again.Email != "test@example.com" || again.State != "ready" ||
		again.RequestCount != 15 || again.SuccessCount != 12 ||
		len(again.Notebooks) != 1 || again.Notebooks[0].ID != "notebook-1" ||
		again.CooldownUntil.IsZero() {
		t.Fatalf("duplicate bind lost original state: %+v", again)
	}
	if len(p.Accounts()) != 1 {
		t.Fatalf("duplicate local Notebook records: %+v", p.Accounts())
	}
	reloaded := NewWithShared(p.root, fakeShared{})
	reused, created, err := reloaded.CreateWithSourceResult(ctx, "", "playground-1")
	if err != nil || created || reused.ID != first.ID || reused.RequestCount != 15 ||
		reused.SuccessCount != 12 || len(reused.Notebooks) != 1 {
		t.Fatalf("persisted bind changed: account=%+v created=%v err=%v", reused, created, err)
	}
}

func TestConcurrentDuplicateBindReturnsOneAccount(t *testing.T) {
	p := NewWithShared(t.TempDir(), fakeShared{})
	const n = 32
	var created atomic.Int32
	var wait sync.WaitGroup
	ids := make(chan string, n)
	errs := make(chan error, n)
	for i := 0; i < n; i++ {
		wait.Add(1)
		go func() {
			defer wait.Done()
			st, wasCreated, err := p.CreateWithSourceResult(context.Background(), "Parallel", "playground-1")
			if err != nil {
				errs <- err
				return
			}
			if wasCreated {
				created.Add(1)
			}
			ids <- st.ID
		}()
	}
	wait.Wait()
	close(ids)
	close(errs)
	for err := range errs {
		t.Fatalf("concurrent bind error: %v", err)
	}
	if created.Load() != 1 {
		t.Fatalf("created %d Notebook accounts, expected 1", created.Load())
	}
	var first string
	for id := range ids {
		if first != "" && id != first {
			t.Fatalf("different local IDs for same Playground source: %q vs %q", id, first)
		}
		first = id
	}
	if len(p.Accounts()) != 1 || len(NewWithShared(p.root, fakeShared{}).Accounts()) != 1 {
		t.Fatalf("concurrent bind produced duplicate or unpersisted accounts: %+v", p.Accounts())
	}
}

