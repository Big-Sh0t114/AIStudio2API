func TestExistingLinkedSourceDoesNotRequireSourceDiscovery(t *testing.T) {
	root := t.TempDir()
	p := NewWithShared(root, fakeShared{})
	first, err := p.CreateWithSource(context.Background(), "Original", "playground-1")
	if err != nil {
		t.Fatal(err)
	}
	offline := NewWithShared(root, failingSharedSources{})
	again, created, err := offline.CreateWithSourceResult(context.Background(), "", "playground-1")
	if err != nil || created || again.ID != first.ID {
		t.Fatalf("lost saved account when Playground discovery failed: %+v created=%v err=%v", again, created, err)
	}
	if _, created, err := offline.CreateWithSourceResult(context.Background(), "", "missing"); err == nil || created {
		t.Fatal("new source bypassed Playground source validation")
	}
}

func TestLegacyDuplicatesArePreservedAndSelectionIsStable(t *testing.T) {
	root := t.TempDir()
	p := NewWithShared(root, fakeShared{})
	low, err := p.CreateWithSource(context.Background(), "Unused", "playground-1")
	if err != nil {
		t.Fatal(err)
	}

	// Simulate existing records generated by older builds. We must not merge
	// their counters or delete their model IDs without explicit user action.
	important := AccountStatus{
		ID: "historical-high-use", Label: "Active model", SourceAccountID: "playground-1",
		RequestCount: 90, SuccessCount: 88, State: "ready",
		Notebooks: []Notebook{{ID: "nb-important", Title: "Important"}},
	}
	p.mu.Lock()
	p.accounts[important.ID] = &account{status: important}
	p.mu.Unlock()
	if err := p.save(); err != nil {
		t.Fatal(err)
	}

	for _, provider := range []*Provider{p, NewWithShared(root, fakeShared{})} {
		reused, created, err := provider.CreateWithSourceResult(context.Background(), "", "playground-1")
		if err != nil || created || reused.ID != important.ID {
			t.Fatalf("legacy dedup selected wrong ID: %+v created=%v err=%v", reused, created, err)
		}
		if len(provider.Accounts()) != 2 {
			t.Fatal("existing IDs were destructively merged")
		}
	}
	if err := p.Remove(low.ID); err != nil {
		t.Fatal(err)
	}
	remains := p.Accounts()
	if len(remains) != 1 || remains[0].ID != important.ID {
		t.Fatalf("manual cleanup removed wrong account: %+v", remains)
	}
}

func TestStandaloneChromeAccountsRemainIndependent(t *testing.T) {
	p := NewWithShared(t.TempDir(), fakeShared{})
	a, createdA, err := p.CreateWithSourceResult(context.Background(), "A", "")
	if err != nil || !createdA {
		t.Fatal(err)
	}
	b, createdB, err := p.CreateWithSourceResult(context.Background(), "B", "")
	if err != nil || !createdB || a.ID == b.ID || len(p.Accounts()) != 2 {
		t.Fatalf("standalone Chrome behavior changed: a=%+v b=%+v err=%v", a, b, err)
	}
}
